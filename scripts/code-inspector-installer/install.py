def expand_path(value: str, base_dir: Path | None = None) -> Path:
    value = value.replace("${HOME}", str(Path.home()))
    expanded = os.path.expandvars(os.path.expanduser(value))
    path = Path(expanded)
    if not path.is_absolute():
        path = (base_dir or REPO_ROOT) / path
    return path.resolve()

