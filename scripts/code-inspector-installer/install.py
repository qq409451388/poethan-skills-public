def generated_codex_rules(identities: list[dict[str, Any]], skill_target: Path) -> str:
    """只允许安装器生成的角色命令 cictl-dev / cictl-insp 越过沙箱访问 Review DB。"""
    lines = [CODEX_RULES_MARKER.rstrip(), ""]
    justification = "Code Inspector 固定身份工具需要访问 Review DB 的 SQLite WAL/SHM 文件。"
    for item in identities:
        if item["role"] in {"developer", "inspector"}:
            command = cictl_command_name(item["role"])
            launcher = str(skill_target.parents[2] / ".agent-review" / "bin" / command)
            fixed_path = item.get("fixed_tool_path")
            patterns = [[command], [launcher]]
            if fixed_path and fixed_path != launcher:
                patterns.append([fixed_path])
            for pattern in patterns:
                encoded_pattern = json.dumps(pattern, ensure_ascii=False, separators=(",", ":"))
                encoded_justification = json.dumps(justification, ensure_ascii=False)
                lines.append(
                    f"prefix_rule(pattern={encoded_pattern}, decision=\"allow\", "
                    f"justification={encoded_justification})"
                )
    return "\n".join(lines) + "\n"

def install_codex_rules(
    codex_home: Path,
    identities: list[dict[str, Any]],
    skill_target: Path,
    force: bool,
) -> Path:
    rules_path = codex_home / "rules" / "code-inspector.rules"
    if rules_path.exists():
        existing = rules_path.read_text(encoding="utf-8")
        if not existing.startswith(CODEX_RULES_MARKER) and not force:
            raise FileExistsError(
                f"目标已存在且不是本安装器生成: {rules_path}，如需替换请使用 --force"
            )
    atomic_write_text(rules_path, generated_codex_rules(identities, skill_target))
    return rules_path

def install_generated_skill(source: Path, target: Path, platform: str, identities: list[dict[str, Any]], home: Path, force: bool) -> None:
    if target.exists() and not target.is_symlink() and not (target / ".code-inspector-generated").exists():
        if not force:
            raise FileExistsError(f"目标已存在且不是本安装器生成: {target}，如需替换请使用 --force")
    target.parent.mkdir(parents=True, exist_ok=True)
    staged = target.parent / f".{target.name}.installing-{uuid.uuid4().hex}"
    staged.mkdir()
    (staged / ".code-inspector-generated").write_text("generated\n", encoding="utf-8")
    (staged / "SKILL.md").write_text(generated_skill_text(platform, identities, target), encoding="utf-8")
    for name in ("references", "scripts", "config"):
        shutil.copytree(
            source / name, staged / name, symlinks=False,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"),
        )
    agents_dir = staged / "agents"
    agents_dir.mkdir(exist_ok=True)
    shutil.copy2(source / "agents" / "openai.yaml", agents_dir / "openai.yaml")
    try:
        replace_staged_path(staged, target)
    finally:
        if staged.exists():
            remove_path(staged)

def remove_legacy_skill_dir(target_root: Path) -> None:
    """删除旧名安装产物，避免新旧两个入口同时出现在平台 Skill 列表里。

    只删除本安装器生成的目录（带 `.code-inspector-generated` 标记），
    同名但非本安装器创建的内容保持不动。
    """
    legacy = target_root / LEGACY_SKILL_DIR_NAME
    if not legacy.is_dir() or not (legacy / ".code-inspector-generated").exists():
        return
    remove_path(legacy)
    print(f"[skills] removed legacy {legacy}", file=sys.stderr)


def tool_role_bindings(tools_config_tool: dict[str, Any], skill_config: dict[str, Any], platform: str) -> dict[str, Any]:
    """解析单个平台实际安装的角色；tools.json 可用可选 roles 字段收窄。"""
    all_bindings = skill_config["bindings"]
    selected = tools_config_tool.get("roles")
    if selected is None:
        return dict(all_bindings)
    if not isinstance(selected, list) or not selected:
        raise ValueError(f"平台 {platform} 的 roles 必须为非空数组")
    unknown = [role for role in selected if role not in all_bindings]
    if unknown:
        raise ValueError(f"平台 {platform} 配置了未绑定角色: {', '.join(unknown)}")
    return {role: all_bindings[role] for role in selected}


def install_role_skills(
    tools_config: dict[str, Any], skill_config: dict[str, Any], source: Path, home: Path, force: bool
) -> None:
    # 角色通用入口保留兼容；平台 Skill 只使用绑定真实操作人的固定路径。
    bindings: dict[str, Any] = {
        binding["alias"]: {
            "alias": binding["alias"], "agent": "legacy-unknown", "role": role,
            "role_policy": skill_config["roles"][role],
            "fixed_tool_path": str(cictl_launcher_path(home, role)),
        }
        for role, binding in skill_config["bindings"].items()
    }
    for platform in skill_config["agents"]:
        tool = tools_config["tools"].get(platform)
        if tool is None:
            raise ValueError(f"Agent 所属工具未配置: {platform}")
        if not tool.get("enabled", False):
            continue
        platform_bindings = tool_role_bindings(tool, skill_config, platform)
        identities = []
        for role, binding in platform_bindings.items():
            suffix = skill_config["roles"][role]["session_selector"]
            alias = f"{platform}-{suffix}"
            fixed_path = write_cictl_launcher(home, role, alias, platform=platform)
            write_cictl_adapter(home, alias)
            item = {"alias": alias, "role": role, "role_policy": skill_config["roles"][role],
                    "fixed_tool_path": str(fixed_path)}
            identities.append(item)
            bindings[alias] = {**item, "agent": platform}
        target_root = expand_path(tool["skills_dir"])
        remove_legacy_skill_dir(target_root)
        target = target_root / skill_config["skill_name"]
        install_generated_skill(source, target, platform, identities, home, force)
        if platform == "codex":
            rules_path = install_codex_rules(target_root.parent, identities, target, force)
            print(f"[rules] {rules_path}", file=sys.stderr)
        print(f"[skills] {target} ({platform}: {', '.join(i['alias'] for i in identities)})", file=sys.stderr)
    bindings["web-human"] = {"alias": "web-human", "agent": "webapp", "role": "human"}
    (home / "config" / "agent-bindings.json").write_text(
        json.dumps(bindings, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    # 角色权限配置是 cictl 运行时拦截越权动作的依据，与 Skill 安装保持同一份。
    (home / "config" / "code-inspector.json").write_text(
        json.dumps(skill_config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

def init_workspace(workspace: Path, home: Path, force: bool) -> None:
    target = workspace / ".agents"
    target.mkdir(parents=True, exist_ok=True)

    templates = SCRIPT_DIR / "templates"
    mapping = {
        templates / "workspace.yaml": target / "workspace.yaml",
        templates / "agents" / "inspector.yaml": target / "inspector.yaml",
        templates / "agents" / "developer.yaml": target / "developer.yaml",
        templates / "agents" / "human.yaml": target / "human.yaml",
    }

    user_home = home.parent.as_posix()
    for src, dst in mapping.items():
        if dst.exists() and not force:
            print(f"[workspace] skip existing {dst}", file=sys.stderr)
            continue
        content = src.read_text(encoding="utf-8")
        content = content.replace("${USER_HOME}", user_home)
        dst.write_text(content, encoding="utf-8")
        print(f"[workspace] created {dst}", file=sys.stderr)

def webtool_launcher_path(home: Path, windows: bool | None = None) -> Path:
    windows = os.name == "nt" if windows is None else windows
    return home / "bin" / ("review-web.cmd" if windows else "review-web")


def link_webtool(home: Path, force: bool, windows: bool | None = None) -> Path:
    """生成人工审查控制台启动器。

    Windows 使用批处理脚本，其他平台使用 Bash 脚本。
    """
    windows = os.name == "nt" if windows is None else windows
    webtool_dir = REPO_ROOT / "apps" / "code-inspector-webtool"
    app_py = webtool_dir / "app.py"
    if not app_py.exists():
        raise FileNotFoundError(f"未找到 webtool 入口: {app_py}")

    launcher = webtool_launcher_path(home, windows)
    launcher.parent.mkdir(parents=True, exist_ok=True)
    if launcher.exists() or launcher.is_symlink():
        if not force and not launcher.is_symlink():
            raise FileExistsError(f"目标已存在: {launcher}，如需替换请使用 --force")
        launcher.unlink()
    if windows:
        launcher.write_text(
            "@echo off\n"
            "setlocal\n"
            f'cd /d "{str(webtool_dir).replace("%", "%%")}"\n'
            "if errorlevel 1 exit /b 1\n"
            'python "app.py" %*\n'
            "exit /b %errorlevel%\n",
            encoding="utf-8",
        )
    else:
        launcher.write_text(
            "#!/usr/bin/env bash\n"
            "set -euo pipefail\n"
            f'cd "{webtool_dir}"\n'
            'exec python3 "app.py" "$@"\n',
            encoding="utf-8",
        )
        launcher.chmod(0o755)
    print(f"[webtool] launcher -> {launcher}", file=sys.stderr)
    return launcher


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Code Inspector Skill 安装器")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--force", action="store_true")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("install")

    p = sub.add_parser("init-workspace")
    p.add_argument("--workspace", type=Path, default=Path.cwd())

    sub.add_parser("migrate")
    sub.add_parser("verify")
    sub.add_parser("install-webtool")
    return parser.parse_args()

def main() -> int:
    args = parse_args()
    try:
        config_path = args.config.resolve()
        config = load_config(config_path)
        source = expand_path(config["skills"]["source_dir"], config_path.parent) / SKILL_DIR_NAME
        skill_config = load_skill_config(source)
        if skill_config["skill_name"] != source.name:
            raise ValueError(
                f"skill_name ({skill_config['skill_name']}) 必须与源目录名 ({source.name}) 一致"
            )
        home = expand_path(skill_config["runtime"]["local_home"])
        db = expand_path(skill_config["runtime"]["database"])

        if args.command == "install":
            ensure_dirs(home)
            shutil.copy2(config_path, home / "config" / "tools.json")
            (home / "config" / "code-inspector.json").write_text(
                json.dumps(skill_config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
            (home / "config" / "runtime.json").write_text(
                json.dumps({"database": str(db)}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
            migration_result = migrate(db, home / "backups")
            link_runtime(home, skill_config, args.force, source)
            install_routing_metadata(source, home, args.force)
            install_role_skills(config, skill_config, source, home, args.force)
            print_result({
                "command": "install", "status": "ok", "home": str(home), "database": str(db),
                "migrations": migration_result["applied"], "backup": migration_result["backup"],
            })

        elif args.command == "init-workspace":
            ensure_dirs(home)
            init_workspace(args.workspace.resolve(), home, args.force)
            print_result({"command": "init-workspace", "status": "ok", "workspace": str(args.workspace.resolve())})

        elif args.command == "migrate":
            ensure_dirs(home)
            migration_result = migrate(db, home / "backups")
            print_result({
                "command": "migrate", "status": "ok", "database": str(db),
                "migrations": migration_result["applied"], "backup": migration_result["backup"],
            })

        elif args.command == "verify":
            schema_ok = False
            migration_ok = False
            runtime_config_ok = False
            if db.exists():
                try:
                    with closing(sqlite3.connect(db)) as conn:
                        required = {
                            "schema_version", "review_task", "review_task_version", "review_issue",
                            "issue_stage", "issue_activity", "agent_audit_log",
                        }
                        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
                        issue_columns = {row[1] for row in conn.execute("PRAGMA table_info(review_issue)")}
                        schema_ok = (
                            required.issubset(tables)
                            and "projection_revision" in issue_columns
                        )
                        installed_version = conn.execute(
                            "SELECT COALESCE(MAX(version), 0) FROM schema_version"
                        ).fetchone()[0]
                        available_versions = [
                            migration_version(path) for path in (SCRIPT_DIR / "migrations").glob("V*.sql")
                        ]
                        migration_ok = bool(available_versions) and installed_version == max(available_versions)
                except sqlite3.Error:
                    schema_ok = False
            runtime_config_path = home / "config" / "runtime.json"
            if runtime_config_path.exists():
                try:
                    installed_runtime = json.loads(runtime_config_path.read_text(encoding="utf-8"))
                    runtime_config_ok = bool(
                        installed_runtime.get("database")
                    )
                except (OSError, ValueError):
                    runtime_config_ok = False
            checks = {
                "database": db.exists(),
                "schema": schema_ok,
                "migrations_current": migration_ok,
                "runtime_cictl": cictl_runtime_path(home).exists(),
                "web_human_adapter": cictl_adapter_path(home, "web-human").exists(),
                "runtime_review_db": (home / "bin" / "review-db.py").exists(),
                "runtime_agent_routing": (home / "bin" / "agent_routing.py").exists(),
                "routing_capabilities": (home / "config" / "agent-capabilities.yml").exists(),
                "runtime_config": runtime_config_ok,
                "skill_config": (home / "config" / "code-inspector.json").exists(),
                "agent_bindings": (home / "config" / "agent-bindings.json").exists(),
            }
            for role, binding in skill_config["bindings"].items():
                alias = binding["alias"]
                checks[f"cictl-launcher:{role}"] = cictl_launcher_path(home, role).exists()
                checks[f"cictl-adapter:{alias}"] = cictl_adapter_path(home, alias).exists()
            for platform in skill_config["agents"]:
                tool = config["tools"].get(platform, {})
                if not tool.get("enabled", False):
                    continue
                for role in tool_role_bindings(tool, skill_config, platform):
                    checks[f"platform-launcher:{platform}:{role}"] = cictl_launcher_path(home, role, platform=platform).exists()
                target_root = expand_path(tool.get("skills_dir", "")) if tool else Path("/")
                target = target_root / skill_config["skill_name"]
                checks[f"skill:{platform}"] = target.is_dir() and (target / ".code-inspector-generated").exists()
            print_result({"command": "verify", "status": "ok" if all(checks.values()) else "failed", "checks": checks})
            if not all(checks.values()):
                return 1

        elif args.command == "install-webtool":
            ensure_dirs(home)
            launcher = link_webtool(home, args.force)
            print_result({
                "command": "install-webtool",
                "status": "ok" if launcher.exists() else "failed",
                "launcher": str(launcher),
                "note": "需先 pip install -r apps/code-inspector-webtool/requirements.txt",
            })
        return 0
    except Exception as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1

if __name__ == "__main__":
    raise SystemExit(main())
